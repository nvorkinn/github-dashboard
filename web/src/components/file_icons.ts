/** The icon for the file at `path`: by its whole name, then its longest known extension, then a plain page. */
export function fileIcon(path: string): string {
  const name = path.slice(path.lastIndexOf("/") + 1).toLowerCase();
  if (path.toLowerCase().startsWith(".github/workflows/") && /\.ya?ml$/.test(name)) return githubActionsWorkflowIcon;
  const named = FILE_NAMES[name];
  if (named) return named;
  for (let dot = name.indexOf(".", 1); dot >= 0; dot = name.indexOf(".", dot + 1)) {
    const icon = EXTENSIONS[name.slice(dot + 1)];
    if (icon) return icon;
  }
  return plainFileIcon;
}

/** The icon for a folder shown as `path` (one name or several, as `a/b/`), by its last name, open or closed. */
export function folderIcon(path: string, open: boolean): string {
  const name = path.replace(/\/$/, "").split("/").pop()?.toLowerCase() ?? "";
  const [closed, opened] = FOLDERS[name] ?? [plainFolderIcon, plainFolderOpenIcon];
  return open ? opened : closed;
}
